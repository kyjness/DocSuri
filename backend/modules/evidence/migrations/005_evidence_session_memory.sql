-- U11 v3 PR 4 — 세션 기억(설계 evidence-agent-v3 §3.4)
--
-- 이전 대화는 **토큰 예산**까지 최근 턴을 그대로 싣고, 밀려난 앞쪽은 요약 한 단락으로
-- 접어 세션에 둔다. 종전의 `_PRIOR_TURNS = 3`은 근거 없이 옮겨온 수치라 폐기했다 —
-- 짧은 턴 셋과 긴 턴 셋이 같은 3이었고 실제로 드는 비용은 열 배 갈렸다.
--
-- 요약이 **세션에 저장되는** 것이 핵심이다. 매 턴 다시 만들면 같은 턴이 세션 길이에 비례해
-- 반복 요약되고, 그 비용은 턴 예산에 잡히지 않은 채 나간다. 여기 한 번 쓰고 이후 턴이
-- 밀려날 때마다 덧붙인다.
--
-- NULL을 허용한다: 아직 아무 턴도 밀려나지 않은 세션과 이 컬럼 이전의 세션이 그것이다.
ALTER TABLE evidence_sessions ADD COLUMN IF NOT EXISTS summary TEXT;
